"""The docs pages get their ``Bound at`` column from an AST scan — pin the scan.

``docs/scripts/gen_limits.py`` and ``gen_throttling.py`` publish the ``Limit`` catalogs
as tables. Neither table can be generated by importing the publisher's intent: the
"which model declares this published row?" answer is spelled in source
(``@limit(*EXCEL_QUOTAS)`` on ``Workbook``, ``@limit(Limits.LIST_VIEW, ...)`` on
``List.get_items``), so it is read with ``ast``. That made the column silently empty
once — the decorator argument is an ``ast.Starred`` for a catalog tuple and an
``ast.Attribute`` for a class attribute, and a scan that understood neither produced a
correct-looking page with no bindings at all. ``mkdocs build --strict`` cannot catch
that, so the scan is pinned here.
"""

from __future__ import annotations

import dataclasses
import importlib.util
import pathlib
import unittest

from office365.limits import catalog
from office365.onedrive.workbooks.quotas import EXCEL_QUOTAS
from office365.onedrive.workbooks.workbook import Workbook
from office365.sharepoint.thresholds import Limits

_REPO_ROOT = pathlib.Path(__file__).resolve().parents[2]
_SCRIPTS = _REPO_ROOT / "docs" / "scripts"

_spec = importlib.util.spec_from_file_location("_doc_limit_bindings", _SCRIPTS / "_limit_bindings.py")
assert _spec is not None and _spec.loader is not None
_bindings_module = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_bindings_module)


class TestLimitBindingScan(unittest.TestCase):
    """``scan_bindings`` reads the source; ``row_attrs`` reads what is imported."""

    @classmethod
    def setUpClass(cls) -> None:
        cls.bindings = _bindings_module.scan_bindings(_REPO_ROOT / "office365")
        cls.names = _bindings_module.row_attrs()

    def test_a_catalog_tuple_argument_is_unwrapped(self) -> None:
        """``@limit(*EXCEL_QUOTAS)`` binds the workbook, not an anonymous starred arg."""
        self.assertIn("Workbook", self.bindings.get("EXCEL_QUOTAS", []))

    def test_a_class_attribute_argument_is_unwrapped(self) -> None:
        """``@limit(Limits.LIST_VIEW, ...)`` binds by the attribute, not by ``Limits``."""
        self.assertIn("List.get_items", self.bindings.get("LIST_VIEW", []))

    def test_a_catalog_row_resolves_to_the_model_that_declares_it(self) -> None:
        """Every workbook quota row points back at :class:`Workbook`."""
        rows = {id(row) for row in EXCEL_QUOTAS}
        bound = {
            _bindings_module.bound_at(row, self.bindings, self.names)
            for row in catalog(product="excel")
            if id(row) in rows
        }
        self.assertEqual(bound, {"Workbook"})

    def test_an_unbound_row_answers_empty_not_a_misbinding(self) -> None:
        """A published row nothing declares has no ``Bound at`` — the page prints ``—``."""
        row = dataclasses.replace(Limits.LIST_VIEW, name="a threshold nobody binds")
        self.assertEqual(_bindings_module.bound_at(row, self.bindings, self.names), "")
        self.assertEqual(
            _bindings_module.bound_at(Limits.LIST_VIEW, self.bindings, self.names), "Folder.get_files, List.get_items"
        )

    def test_every_declared_row_of_a_bound_class_is_bound(self) -> None:
        """The scan is not a partial answer: all workbook rows are accounted for."""
        self.assertEqual({id(row) for row in Workbook.declared_limits()}, {id(row) for row in EXCEL_QUOTAS})
